#!/usr/bin/env python3
"""Write backend/src/decks/fontWidths.ts: Arial's character widths, for fitting deck text to its boxes.

Decks are set in Arial (backend/src/decks/render.ts) and no font is embedded, so the server measures
text from a table of advance widths instead of a font file. Liberation Sans is metric-compatible with
Arial (same advance width for every character), so its widths are Arial's. Only numbers are written:
no font data, no glyphs. Run it where Liberation Sans is installed (Debian/Ubuntu: fonts-liberation):

    python3 tools/deck_font_widths.py [path to LiberationSans-Regular.ttf] [path to LiberationSans-Bold.ttf]
"""
import sys
from pathlib import Path

from PIL import ImageFont

DEFAULT_DIR = Path("/usr/share/fonts/truetype/liberation")
OUT = Path(__file__).resolve().parent.parent / "backend" / "src" / "decks" / "fontWidths.ts"
UNITS = 2048  # Liberation Sans and Arial: 2048 units per em

# Latin (every deck language but the Cyrillic and Greek ones), Romanian comma letters, Greek, Cyrillic,
# and the punctuation and signs decks use.
RANGES = [
    (0x20, 0x7E), (0xA0, 0x17F), (0x218, 0x21B), (0x384, 0x3CE), (0x400, 0x45F), (0x490, 0x491),
    (0x2013, 0x2014), (0x2018, 0x201E), (0x2022, 0x2022), (0x2026, 0x2026), (0x2030, 0x2030), (0x2032, 0x2033),
    (0x20AC, 0x20AC), (0x2116, 0x2116), (0x2122, 0x2122), (0x2190, 0x2193), (0x2212, 0x2212), (0x25A0, 0x25A0),
]


def widths(font: ImageFont.FreeTypeFont, start: int, end: int) -> list[int]:
    # Thousandths of an em, as PowerPoint's own metrics are usually given.
    return [round(font.getlength(chr(c)) * 1000 / UNITS) for c in range(start, end + 1)]


def main() -> None:
    regular_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DIR / "LiberationSans-Regular.ttf"
    bold_path = Path(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_DIR / "LiberationSans-Bold.ttf"
    regular = ImageFont.truetype(str(regular_path), UNITS)
    bold = ImageFont.truetype(str(bold_path), UNITS)
    lines = [
        "// Generated by tools/deck_font_widths.py; don't edit by hand.",
        "// Arial's advance widths in thousandths of an em, read from Liberation Sans (metric-compatible with",
        "// Arial). Numbers only: no font data. Used to fit deck text to its boxes (render.ts).",
        "",
        "/** [first code point, regular widths, bold widths] */",
        "export const WIDTH_RANGES: readonly (readonly [number, readonly number[], readonly number[]])[] = [",
    ]
    for start, end in RANGES:
        lines.append(f"  [0x{start:04X}, [{', '.join(map(str, widths(regular, start, end)))}],")
        lines.append(f"    [{', '.join(map(str, widths(bold, start, end)))}]],")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
