"""Generate Doddy Web's design tokens and copy its brand files from the iPhone app (ADR-585).

The web app shows what the iPhone app shows, so nothing here is drawn or picked by hand:
  - web/src/styles/tokens.css   colours from UploadedTokens.swift (the palette `Theme` uses), light
                                and dark, plus the app's metrics from CandidateTokens.swift
  - web/public/brand/wordmark.svg              the app's DoddyWordmark (ADR-562), byte for byte
  - web/public/brand/doddy-crosslegged@2x.png  the pack's WholeDoddy_crosslegged pose (Home's
  - web/public/brand/doddy-crosslegged@3x.png  Doddy, ADR-545), byte for byte
  - web/public/favicon.png                     the site's favicon (Doddy's face, ADR-565)

    python3 -I tools/gen_web_assets.py          write them
    python3 -I tools/gen_web_assets.py --check  exit 1 if any is missing or out of date
"""
from pathlib import Path
import re
import sys

root = Path(__file__).resolve().parents[1]
tokens_swift = root / "Packages/DoddyCore/Sources/DoddyDesignTokens/UploadedTokens.swift"
metrics_swift = root / "Packages/DoddyCore/Sources/DoddyDesignTokens/CandidateTokens.swift"
assets = root / "DoddyApp/Resources/Assets.xcassets"
copies = {
    root / "web/public/brand/wordmark.svg": assets / "DoddyWordmark.imageset/wordmark.svg",
    root / "web/public/brand/doddy-crosslegged@2x.png": assets / "WholeDoddy_crosslegged.imageset/art@2x.png",
    root / "web/public/brand/doddy-crosslegged@3x.png": assets / "WholeDoddy_crosslegged.imageset/art@3x.png",
    root / "web/public/favicon.png": root / "site/assets/doddy-favicon.png",
}
css_out = root / "web/src/styles/tokens.css"

pairs = re.findall(r'case \.(\w+): pair = \("(#[0-9A-Fa-f]{6})", "(#[0-9A-Fa-f]{6})"\)', tokens_swift.read_text())
if len(pairs) != 9:
    sys.exit(f"FAIL: expected 9 colour roles in {tokens_swift.relative_to(root)}, found {len(pairs)}")

metrics_text = metrics_swift.read_text()


def metric(name):
    match = re.search(rf"static let {name} = ([0-9.]+)", metrics_text)
    if not match:
        sys.exit(f"FAIL: {name} not found in {metrics_swift.relative_to(root)}")
    return float(match.group(1))


spacing = re.search(r"static let spacing: \[Double\] = \[([0-9., ]+)\]", metrics_text)
if not spacing:
    sys.exit(f"FAIL: spacing not found in {metrics_swift.relative_to(root)}")
steps = [float(v) for v in spacing.group(1).split(",")]


def css_name(role):
    return "--" + re.sub(r"(?<!^)([A-Z])", r"-\1", role).lower()


def colours(index, indent):
    return "\n".join(f"{indent}{css_name(role)}: {values[index]};" for role, *values in pairs)


def px(value):
    return f"{value:g}px"


space = "\n".join(f"  --space-{i + 1}: {px(v)};" for i, v in enumerate(steps))
css = f"""/* Generated by tools/gen_web_assets.py from UploadedTokens.swift and CandidateTokens.swift. Do not edit by hand. */
:root {{
  color-scheme: light dark;
{colours(0, "  ")}
  --tap-target: {px(metric("minimumTapTarget"))};
  --control-height: {px(metric("primaryControlHeight"))};
  --gutter: {px(metric("horizontalMargin"))};
{space}
}}
@media (prefers-color-scheme: dark) {{
  :root:not([data-theme="light"]) {{
{colours(1, "    ")}
  }}
}}
:root[data-theme="dark"] {{
{colours(1, "  ")}
}}
"""

if "--check" in sys.argv:
    problems = []
    if not css_out.is_file() or css_out.read_text() != css:
        problems.append(str(css_out.relative_to(root)))
    for target, source in copies.items():
        if not target.is_file() or target.read_bytes() != source.read_bytes():
            problems.append(str(target.relative_to(root)))
    if problems:
        sys.exit("FAIL: out of date (run python3 -I tools/gen_web_assets.py): " + ", ".join(problems))
    print(f"PASS: web tokens match {len(pairs)} app colour roles; {len(copies)} brand files match the app's.")
else:
    css_out.parent.mkdir(parents=True, exist_ok=True)
    css_out.write_text(css)
    for target, source in copies.items():
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(source.read_bytes())
    print(f"Wrote {css_out.relative_to(root)} ({len(pairs)} roles) and {len(copies)} brand files.")
