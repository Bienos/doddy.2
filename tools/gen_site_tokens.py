"""Generate site/tokens.css from the app's colour tokens so the landing page and the app share one palette.

Source of truth: Packages/DoddyCore/Sources/DoddyDesignTokens/CandidateTokens.swift (the `pair` table).
    python3 -I tools/gen_site_tokens.py          write site/tokens.css
    python3 -I tools/gen_site_tokens.py --check  exit 1 if site/tokens.css is out of date
"""
from pathlib import Path
import re, sys

root = Path(__file__).resolve().parents[1]
swift = root / "Packages/DoddyCore/Sources/DoddyDesignTokens/CandidateTokens.swift"
out = root / "site/tokens.css"

pairs = re.findall(r'case \.(\w+): \("(#[0-9A-Fa-f]{6})", "(#[0-9A-Fa-f]{6})"\)', swift.read_text())
if len(pairs) < 9:
    sys.exit(f"FAIL: expected 9 colour roles in {swift.relative_to(root)}, found {len(pairs)}")

def css_name(role):
    return "--" + re.sub(r"(?<!^)([A-Z])", r"-\1", role).lower()

def block(index, indent):
    return "\n".join(f"{indent}{css_name(role)}: {values[index]};" for role, *values in pairs)

# Light on bare :root; dark under the OS setting unless a page sets data-theme="light", and again for data-theme="dark".
css = f"""/* Generated by tools/gen_site_tokens.py from CandidateTokens.swift. Do not edit by hand. */
:root {{
  color-scheme: light;
{block(0, "  ")}
}}

@media (prefers-color-scheme: dark) {{
  :root:not([data-theme="light"]) {{
    color-scheme: dark;
{block(1, "    ")}
  }}
}}

:root[data-theme="dark"] {{
  color-scheme: dark;
{block(1, "  ")}
}}
"""

if "--check" in sys.argv:
    if not out.is_file() or out.read_text() != css:
        sys.exit("FAIL: site/tokens.css is out of date; run python3 -I tools/gen_site_tokens.py")
    print(f"PASS: site/tokens.css matches {len(pairs)} app colour roles.")
else:
    out.write_text(css)
    print(f"Wrote {out.relative_to(root)} ({len(pairs)} roles).")
